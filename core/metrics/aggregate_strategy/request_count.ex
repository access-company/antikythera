use Croma
alias AntikytheraCore.Metrics.AggregateStrategy, as: Strategy

defmodule Strategy.RequestCount do
  @moduledoc """
  Aggregate strategy for request counts.
  This calculates the following values from HTTP status codes of responses within a time window:

  - total number of requests
  - number of requests that result in 4XX response (client error)
  - number of requests that result in 401 response (unauthorized); these are also counted in 4XX
  - number of requests that result in 5XX response (server error)

  Note that, strictly speaking, numbers generated by this aggreagate strategy do not include invalid requests
  that are rejected by antikythera before arriving at gear's controller action,
  i.e. requests which do not match any of the defined routes, requests with malformed body, etc.
  """

  @behaviour Strategy.Behaviour
  alias Antikythera.Http.Status

  @typep data_t :: {pos_integer, non_neg_integer, non_neg_integer, non_neg_integer}

  # Data without the 401 count. `AntikytheraCore.MetricsUploader` may hold data in this format
  # when this module is replaced by hot code upgrade, since process states are not converted.
  @typep data_without_401_t :: {pos_integer, non_neg_integer, non_neg_integer}

  @impl true
  defun init(status :: v[Status.Int.t()]) :: data_t do
    {inc_4xx, inc_401, inc_5xx} = increments(status)
    {1, inc_4xx, inc_401, inc_5xx}
  end

  @impl true
  defun merge(data :: data_t | data_without_401_t, status :: v[Status.Int.t()]) :: data_t do
    {count_total, count_4xx, count_401, count_5xx} = with_401_count(data)
    {inc_4xx, inc_401, inc_5xx} = increments(status)
    {count_total + 1, count_4xx + inc_4xx, count_401 + inc_401, count_5xx + inc_5xx}
  end

  defunp with_401_count(data :: data_t | data_without_401_t) :: data_t do
    {count_total, count_4xx, count_5xx} -> {count_total, count_4xx, 0, count_5xx}
    data -> data
  end

  defunp increments(status :: Status.Int.t()) :: {0 | 1, 0 | 1, 0 | 1} do
    case status do
      401 -> {1, 1, 0}
      _ when div(status, 100) == 4 -> {1, 0, 0}
      _ when div(status, 100) == 5 -> {0, 0, 1}
      _ -> {0, 0, 0}
    end
  end

  @impl true
  defun results(data :: data_t | data_without_401_t) :: Strategy.results_t() do
    {count_total, count_4xx, count_401, count_5xx} = with_401_count(data)

    [
      total: count_total,
      "4XX": count_4xx,
      "401": count_401,
      "5XX": count_5xx
    ]
  end
end
